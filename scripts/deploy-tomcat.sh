#!/usr/bin/env bash
# Deploys target/yoga-portal.war to a local Tomcat 10 through a context descriptor.
# The descriptor also injects the environment label as a servlet-context parameter,
# which Spring Boot reads as the property `app.environment`.
#
# Env vars:
#   CATALINA_BASE    Tomcat base dir   (default: Homebrew tomcat@10)
#   APP_ENVIRONMENT  dev | qa | staging (default: dev)
#   CONTEXT_PATH     URL context path   (default: yoga)
#   DEPLOY_DIR       where WARs are kept (default: ~/yoga-deploy)
set -euo pipefail

CATALINA_BASE="${CATALINA_BASE:-/opt/homebrew/opt/tomcat@10/libexec}"
APP_ENVIRONMENT="${APP_ENVIRONMENT:-dev}"
CONTEXT_PATH="${CONTEXT_PATH:-yoga}"
DEPLOY_DIR="${DEPLOY_DIR:-$HOME/yoga-deploy}"
WAR="target/yoga-portal.war"

[ -f "$WAR" ] || { echo "ERROR: $WAR not found - run 'mvn package' first" >&2; exit 1; }

STAMP="$(date +%Y%m%d%H%M%S)"
mkdir -p "$DEPLOY_DIR" "$CATALINA_BASE/conf/Catalina/localhost"

# Keep each release, point the context at the newest one.
RELEASE_WAR="$DEPLOY_DIR/yoga-portal-$STAMP.war"
cp "$WAR" "$RELEASE_WAR"
ln -sfn "$RELEASE_WAR" "$DEPLOY_DIR/current.war"

cat > "$CATALINA_BASE/conf/Catalina/localhost/$CONTEXT_PATH.xml" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/deploy-tomcat.sh at $STAMP (Jenkins build ${BUILD_NUMBER:-local}) -->
<Context docBase="$RELEASE_WAR" reloadable="false">
    <Parameter name="app.environment" value="$APP_ENVIRONMENT" override="false"/>
</Context>
XML

# Keep only the 5 newest releases
ls -1t "$DEPLOY_DIR"/yoga-portal-*.war 2>/dev/null | tail -n +6 | while read -r old; do rm -f "$old"; done

echo "Deployed $RELEASE_WAR"
echo "Context  $CATALINA_BASE/conf/Catalina/localhost/$CONTEXT_PATH.xml (environment=$APP_ENVIRONMENT)"
